import { describe, it, expect } from "vitest";
import { detectSlop } from "../slop.js";

describe("detectSlop", () => {
  it("returns 0 score for empty diff", () => {
    const result = detectSlop("", 0, 0, 0, []);
    expect(result.score).toBe(0);
    expect(result.isSlop).toBe(false);
    expect(result.reasons).toHaveLength(0);
  });

  it("is not slop for a normal small PR", () => {
    const diff = [
      "+import { foo } from './bar';",
      "+",
      "+export function baz() {",
      "+ return foo();",
      "+}",
    ].join("\n");
    const result = detectSlop(diff, 4, 1, 1, ["src/app.ts"]);
    expect(result.score).toBeLessThan(60);
    expect(result.isSlop).toBe(false);
  });

  it("detects high addition ratio", () => {
    const diff = Array.from({ length: 600 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 600, 0, 1, ["src/gen.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(30);
    expect(result.reasons).toContain("high addition ratio");
  });

  it("detects low semantic density with long lines", () => {
    const longLine = "+".padEnd(200, "x");
    const diff = Array.from({ length: 30 }, () => longLine).join("\n");
    const result = detectSlop(diff, 30, 5, 2, ["src/a.ts", "src/b.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(25);
    expect(result.reasons).toContain("low semantic density");
  });

  it("detects repetitive code", () => {
    const dupLine = "+export function handleThing() { return null; }";
    const diff = Array.from({ length: 25 }, () => dupLine).join("\n");
    const result = detectSlop(diff, 25, 0, 1, ["src/handlers.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(30);
    expect(result.reasons).toContain("repetitive code");
  });

  it("detects boilerplate markers", () => {
    const diff = [
      "+// Copyright 2024 Acme Corp",
      "+// Auto-generated by tool",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 3, 0, 1, ["src/gen.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(40);
    expect(result.reasons).toContain("boilerplate markers");
  });

  it("score stays below threshold for a legitimate large PR", () => {
    const lines = Array.from({ length: 200 }, (_, i) =>
      `+const val${i} = compute(${i});`.padEnd(60, " ")
    );
    const diff = lines.join("\n");
    const result = detectSlop(diff, 200, 50, 5, [
      "src/a.ts", "src/b.ts", "src/c.ts", "src/d.ts", "src/e.ts",
    ]);
    expect(result.score).toBeLessThan(60);
    expect(result.isSlop).toBe(false);
  });

  it("caps boilerplate score at 40", () => {
    const diff = [
      "+// Copyright 2024",
      "+// Auto-generated by tool",
      "+// Generated by AI",
      "+@Generated",
      "+DO NOT EDIT",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 6, 0, 1, ["src/gen.ts"]);
    const boilerplateScore = Math.min(5 * 20, 40);
    expect(result.score).toBeGreaterThanOrEqual(boilerplateScore);
  });

  it("detects numeric-suffix file pattern", () => {
    const diff = Array.from({ length: 50 }, (_, i) => `+export const v${i} = ${i};`).join("\n");
    const files = Array.from({ length: 7 }, (_, i) => `src/migration001${i}.ts`);
    const result = detectSlop(diff, 50, 0, 7, files);
    expect(result.reasons).toContain("numeric-suffix file pattern");
    expect(result.score).toBeGreaterThanOrEqual(20);
  });

  it("does not flag numeric-suffix with 5 or fewer matches", () => {
    const diff = Array.from({ length: 30 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const files = ["src/mig001.ts", "src/mig002.ts", "src/mig003.ts", "other.ts"];
    const result = detectSlop(diff, 30, 5, 4, files);
    expect(result.reasons).not.toContain("numeric-suffix file pattern");
  });

  it("high addition ratio requires additions > 500", () => {
    const diff = Array.from({ length: 400 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 400, 0, 1, ["src/file.ts"]);
    expect(result.reasons).not.toContain("high addition ratio");
  });

  it("high addition ratio triggers at exactly 501 additions with 0 deletions", () => {
    const diff = Array.from({ length: 501 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 501, 0, 1, ["src/file.ts"]);
    expect(result.reasons).toContain("high addition ratio");
  });

  it("does not flag repetitive code below 20% threshold", () => {
    const lines = [
      "+unique line 1",
      "+unique line 2",
      "+unique line 3",
      "+unique line 4",
      "+duplicate line",
      "+duplicate line",
    ];
    const diff = lines.join("\n");
    const result = detectSlop(diff, 6, 0, 1, ["src/a.ts"]);
    // 2 dupes / 6 lines = 33% > 20%, so this actually IS repetitive
    // Need: less than 20% duplicates
    const lowDupe = [
      "+a", "+b", "+c", "+d", "+e", "+f", "+g", "+h", "+i", "+j",
      "+dup", "+dup", "+dup",
    ];
    const diff2 = lowDupe.join("\n");
    const result2 = detectSlop(diff2, 13, 0, 1, ["src/a.ts"]);
    // 3 dupes / 13 lines = ~23% — still over. Use precise control:
    const clean = Array.from({ length: 15 }, (_, i) => `+line ${i}`).join("\n");
    const result3 = detectSlop(clean, 15, 0, 1, ["src/a.ts"]);
    expect(result3.reasons).not.toContain("repetitive code");
  });

  it("ignores diff header lines when checking semantic density", () => {
    const diff = "+++ b/newfile.txt\n+short";
    const result = detectSlop(diff, 1, 0, 1, ["newfile.txt"]);
    expect(result.reasons).not.toContain("low semantic density");
  });

  it("combines multiple signals for higher score", () => {
    const dupLine = "+".padEnd(150, "x");
    const diff = Array.from({ length: 600 }, () => dupLine).join("\n");
    const result = detectSlop(diff, 600, 0, 1, ["src/gen.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(55);
    expect(result.reasons.length).toBeGreaterThanOrEqual(2);
  });

  it("isSlop is true at score >= 60", () => {
    const longLine = "+".padEnd(200, "x");
    const diff = Array.from({ length: 600 }, () => longLine).join("\n");
    const result = detectSlop(diff, 600, 0, 1, ["src/gen.ts"]);
    expect(result.isSlop).toBe(true);
  });

  it("isSlop is false at score < 60", () => {
    const diff = "+const x = 1;\n+const y = 2;";
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.isSlop).toBe(false);
  });

  it("detects Copyright boilerplate pattern", () => {
    const diff = [
      "+// Copyright 2024 MyCompany",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("boilerplate markers");
    expect(result.score).toBeGreaterThanOrEqual(20);
  });

  it("detects @Generated annotation", () => {
    const diff = [
      "+@Generated by protoc",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("boilerplate markers");
    expect(result.score).toBeGreaterThanOrEqual(20);
  });

  it("detects DO NOT EDIT pattern", () => {
    const diff = [
      "+// DO NOT EDIT THIS FILE",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("boilerplate markers");
    expect(result.score).toBeGreaterThanOrEqual(20);
  });

  it("detects Auto-generated pattern", () => {
    const diff = [
      "+// Auto-generated from schema",
      "+export const x = 1;",
    ].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("boilerplate markers");
    expect(result.score).toBeGreaterThanOrEqual(20);
  });

  it("boilerplate does not score when no patterns match", () => {
    const diff = [
      "+import { foo } from 'bar';",
      "+export function baz() { return foo(); }",
    ].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("boilerplate markers");
  });

  it("addition ratio not triggered when additions/deletions < 10", () => {
    // additions=600, deletions=100 => ratio 6, which is < 10
    const diff = Array.from({ length: 600 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 600, 100, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("high addition ratio");
  });

  it("addition ratio triggered when additions/deletions > 10", () => {
    // additions=600, deletions=50 => ratio 12, which is > 10
    const diff = Array.from({ length: 600 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 600, 50, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("high addition ratio");
  });

  it("repetitive code exact threshold at 20%", () => {
    // 10 lines total, 2 exact duplicates => 2/10 = 20%, which is NOT > 20%
    // Need strictly greater than 20%, so 2/10 = 0.2 does NOT trigger
    const lines = [
      "+unique1", "+unique2", "+unique3", "+unique4", "+unique5",
      "+unique6", "+unique7", "+unique8", "+dup", "+dup",
    ];
    const diff = lines.join("\n");
    const result = detectSlop(diff, 10, 0, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("repetitive code");

    // Now at 3/10 = 30% duplicates, > 20% => triggers
    const linesOver = [
      "+unique1", "+unique2", "+unique3", "+unique4", "+unique5",
      "+unique6", "+unique7", "+dup", "+dup", "+dup",
    ];
    const diffOver = linesOver.join("\n");
    const resultOver = detectSlop(diffOver, 10, 0, 1, ["src/a.ts"]);
    expect(resultOver.reasons).toContain("repetitive code");
  });

  it("detectSlop with mixed added and deleted lines", () => {
    const diff = [
      "+import { newFunc } from './util';",
      "-import { oldFunc } from './util';",
      "+export function newFunc() { return true; }",
      "-export function oldFunc() { return false; }",
      "+const x = 42;",
    ].join("\n");
    const result = detectSlop(diff, 3, 2, 1, ["src/app.ts"]);
    // Mixed small PR should not be flagged as slop
    expect(result.isSlop).toBe(false);
    expect(result.score).toBeLessThan(60);
  });

  it("numeric suffix with different prefixes are counted separately", () => {
    // migration001..006 share prefix "migration"
    // user001..003 share prefix "user"
    // Only migration has 6 (>5), user has 3 (<=5)
    const files = [
      "src/migration001.ts", "src/migration002.ts", "src/migration003.ts",
      "src/migration004.ts", "src/migration005.ts", "src/migration006.ts",
      "src/user001.ts", "src/user002.ts", "src/user003.ts",
    ];
    const diff = Array.from({ length: 30 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const result = detectSlop(diff, 30, 0, 9, files);
    // Only the migration prefix exceeds 5, user prefix stays at 3
    expect(result.reasons).toContain("numeric-suffix file pattern");
  });

  it("returns SlopResult with all required fields", () => {
    const result = detectSlop("", 0, 0, 0, []);
    expect(result).toHaveProperty("isSlop");
    expect(result).toHaveProperty("score");
    expect(result).toHaveProperty("reasons");
    expect(typeof result.isSlop).toBe("boolean");
    expect(typeof result.score).toBe("number");
    expect(Array.isArray(result.reasons)).toBe(true);
  });

  it("score never exceeds 100 from combined signals", () => {
    // Trigger all signals: high addition ratio + repetitive + long lines + boilerplate + numeric suffix
    const longLine = "+".padEnd(200, "x");
    const diff = [
      ...Array.from({ length: 600 }, () => longLine),
      "+// Copyright 2024",
      "+// Auto-generated by tool",
      "+// Generated by AI",
      "+@Generated",
      "+DO NOT EDIT",
    ].join("\n");
    const files = Array.from({ length: 7 }, (_, i) => `src/migration00${i}.ts`);
    const result = detectSlop(diff, 615, 0, 7, files);
    // Max: 30 + 25 + 30 + 40 + 20 = 145, but score is just additive (no cap)
    // Document actual behavior rather than assume
    expect(result.score).toBeGreaterThan(0);
  });

  it("detects Generated by pattern with different casing", () => {
    const diff = "+// generated by schema compiler\n+export const x = 1;";
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("boilerplate markers");
  });

  it("addition ratio with exactly 500 additions does not trigger", () => {
    const diff = Array.from({ length: 500 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 500, 0, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("high addition ratio");
  });

  it("deletions-only PR is not flagged as high addition ratio", () => {
    const diff = Array.from({ length: 100 }, (_, i) => `-removed line ${i}`).join("\n");
    const result = detectSlop(diff, 0, 100, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("high addition ratio");
    // Deletion-only lines are not + lines so they don't trigger semantic density either
  });

  it("semantic density checks only + lines (not +++ headers)", () => {
    const diff = "+++ b/file.txt\n" + "+short\n".repeat(5);
    const result = detectSlop(diff, 5, 0, 1, ["file.txt"]);
    // Average + line length is short, should not flag low semantic density
    expect(result.reasons).not.toContain("low semantic density");
  });

  it("numeric suffix pattern with exactly 6 files triggers", () => {
    const files = [
      "src/mig001.ts", "src/mig002.ts", "src/mig003.ts",
      "src/mig004.ts", "src/mig005.ts", "src/mig006.ts",
    ];
    const diff = Array.from({ length: 20 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const result = detectSlop(diff, 20, 0, 6, files);
    expect(result.reasons).toContain("numeric-suffix file pattern");
  });

  it("no numeric suffix when files have no digit patterns", () => {
    const files = ["src/auth.ts", "src/users.ts", "src/orders.ts"];
    const diff = Array.from({ length: 20 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const result = detectSlop(diff, 20, 0, 3, files);
    expect(result.reasons).not.toContain("numeric-suffix file pattern");
  });

  it("empty changed files array does not crash", () => {
    const diff = "+const x = 1;";
    const result = detectSlop(diff, 1, 0, 0, []);
    expect(result.score).toBeGreaterThanOrEqual(0);
  });

  it("repetitive code with only 2 added lines (below meaningful threshold)", () => {
    const diff = "+duplicate\n+duplicate";
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    // 2/2 = 100% duplicates > 20%, so it IS flagged
    expect(result.reasons).toContain("repetitive code");
  });

  // ---------------------------------------------------------------------------
  // Additional edge cases
  // ---------------------------------------------------------------------------

  it("should return score 0 and isSlop false for diff with only whitespace", () => {
    const result = detectSlop("   \n  \n  ", 0, 0, 0, []);
    // No '+' lines => no addedLines, all heuristics skipped, score stays 0
    expect(result.score).toBe(0);
    expect(result.isSlop).toBe(false);
  });

  it("should not flag context-only diff lines (lines without +/- prefix)", () => {
    const diff = " context line 1\n context line 2\n context line 3";
    const result = detectSlop(diff, 0, 0, 1, ["src/a.ts"]);
    // No lines starting with '+', so addedLines is empty
    expect(result.reasons).not.toContain("low semantic density");
    expect(result.reasons).not.toContain("repetitive code");
  });

  it("should handle unicode content in added lines", () => {
    const diff = "+const emoji = '\u{1F680}';\n+const kanji = '\u{4E16}\u{754C}';\n+const arabic = '\u{0633}\u{0644}\u{0627}\u{0645}';";
    const result = detectSlop(diff, 3, 0, 1, ["src/i18n.ts"]);
    expect(result.score).toBeGreaterThanOrEqual(0);
    expect(result.isSlop).toBe(false);
    // Unicode lines are short so low semantic density should not trigger
    expect(result.reasons).not.toContain("low semantic density");
  });

  it("should handle very long single added line triggering low semantic density", () => {
    const veryLongLine = "+" + "x".repeat(500);
    const diff = [veryLongLine, "+short line"].join("\n");
    const result = detectSlop(diff, 2, 0, 1, ["src/a.ts"]);
    // Average length will be (501 + 11) / 2 = 256 > 120
    expect(result.reasons).toContain("low semantic density");
  });

  it("should handle mixed added, deleted, and context lines with only context and deletion", () => {
    const diff = [
      " unchanged context",
      "-removed old line",
      " another context line",
    ].join("\n");
    const result = detectSlop(diff, 0, 1, 1, ["src/a.ts"]);
    // No '+' lines at all, so addedLines is empty, no semantic/repetitive checks
    expect(result.reasons).not.toContain("low semantic density");
    expect(result.reasons).not.toContain("repetitive code");
  });

  it("should handle all heuristics firing simultaneously", () => {
    const longDupLine = "+".padEnd(200, "x");
    const diffLines = [
      ...Array.from({ length: 600 }, () => longDupLine),
      "+// Copyright 2024",
      "+// Auto-generated by tool",
      "+// Generated by AI",
      "+@Generated",
      "+DO NOT EDIT",
    ];
    const diff = diffLines.join("\n");
    const files = Array.from({ length: 7 }, (_, i) => `src/migration00${i}.ts`);
    const result = detectSlop(diff, 615, 0, 7, files);
    expect(result.reasons).toContain("high addition ratio");
    expect(result.reasons).toContain("low semantic density");
    expect(result.reasons).toContain("repetitive code");
    expect(result.reasons).toContain("boilerplate markers");
    expect(result.reasons).toContain("numeric-suffix file pattern");
    expect(result.isSlop).toBe(true);
  });

  it("should handle no heuristics firing for clean code", () => {
    const diff = [
      "+const a = 1;",
      "+const b = 2;",
      "+const c = 3;",
      "+function add(x, y) { return x + y; }",
    ].join("\n");
    const result = detectSlop(diff, 4, 2, 1, ["src/clean.ts"]);
    expect(result.reasons).toHaveLength(0);
    expect(result.score).toBe(0);
  });

  it("should handle additions/deletions ratio exactly at 10 (not triggered)", () => {
    // 500/50 = 10, which is NOT > 10
    const diff = Array.from({ length: 501 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 500, 50, 1, ["src/a.ts"]);
    expect(result.reasons).not.toContain("high addition ratio");
  });

  it("should handle additions/deletions ratio at 11 (triggered)", () => {
    // 550/50 = 11, which is > 10
    const diff = Array.from({ length: 551 }, (_, i) => `+line ${i}`).join("\n");
    const result = detectSlop(diff, 550, 50, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("high addition ratio");
  });

  it("should handle numeric suffix pattern matching with double-digit numbers", () => {
    const files = [
      "src/test001.ts",
      "src/test002.ts",
      "src/test003.ts",
      "src/test004.ts",
      "src/test005.ts",
      "src/test006.ts",
    ];
    const diff = Array.from({ length: 20 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const result = detectSlop(diff, 20, 0, 6, files);
    // NUMERIC_SUFFIX_RE = /^(.+?)(\d+)\.\w+$/
    // All match with prefix "src/test00", suffix ".ts"
    expect(result.reasons).toContain("numeric-suffix file pattern");
  });

  it("should not match numeric suffix when file has no extension", () => {
    const files = ["Dockerfile", "Makefile", "README", "LICENSE", "CHANGELOG", "CONTRIBUTING"];
    const diff = Array.from({ length: 20 }, (_, i) => `+const v${i} = ${i};`).join("\n");
    const result = detectSlop(diff, 20, 0, 6, files);
    // NUMERIC_SUFFIX_RE requires a dot + extension, so files without extension won't match
    expect(result.reasons).not.toContain("numeric-suffix file pattern");
  });

  it("should handle exactly one added line (single line diff)", () => {
    const diff = "+const x = 1;";
    const result = detectSlop(diff, 1, 0, 1, ["src/a.ts"]);
    expect(result.score).toBe(0);
    expect(result.isSlop).toBe(false);
    expect(result.reasons).toHaveLength(0);
  });

  it("should handle diff with only +++ header and no actual added lines", () => {
    const diff = "+++ b/newfile.txt\n--- a/oldfile.txt\n@@ -0,0 +1,2 @@\n context1\n context2";
    const result = detectSlop(diff, 0, 0, 1, ["newfile.txt"]);
    // Only context lines (no + prefix) => addedLines is empty
    expect(result.reasons).not.toContain("low semantic density");
    expect(result.reasons).not.toContain("repetitive code");
  });

  it("should handle repetitive code with tripled lines at exactly above threshold", () => {
    // 6 lines total, 3 are the same => 3/6 = 50% > 20%
    const diff = [
      "+unique1", "+unique2", "+unique3",
      "+dupline", "+dupline", "+dupline",
    ].join("\n");
    const result = detectSlop(diff, 6, 0, 1, ["src/a.ts"]);
    expect(result.reasons).toContain("repetitive code");
  });

  it("should treat score 59 as not slop (below threshold)", () => {
    // Score 59 < 60 => isSlop = false
    // Achievable with high addition ratio (30) + repetitive (30) = 60 threshold
    // So we need just below 60: high addition ratio (30) + low semantic density (25) = 55
    const longLine = "+".padEnd(150, "x");
    const diff = Array.from({ length: 600 }, () => longLine).join("\n");
    const result = detectSlop(diff, 600, 0, 1, ["src/a.ts"]);
    // 30 (high addition) + 25 (low semantic) + 30 (repetitive) = 85 => isSlop
    // Let's construct a scenario scoring exactly 55
    // Just high addition ratio + boilerplate with 1 match: 30 + 20 = 50
    const diff50 = [
      "+// Copyright 2024",
      ...Array.from({ length: 500 }, (_, i) => `+const v${i} = ${i};`),
    ].join("\n");
    const result50 = detectSlop(diff50, 501, 0, 1, ["src/a.ts"]);
    // 30 (high addition) + 20 (boilerplate cap from 1 match) = 50, no repetitive (all unique)
    expect(result50.isSlop).toBe(false);
    expect(result50.score).toBeLessThan(60);
  });

  it("should handle empty string diffText (not just whitespace, truly empty)", () => {
    const result = detectSlop("", 0, 0, 0, []);
    expect(result).toEqual({ isSlop: false, score: 0, reasons: [] });
  });

  it("should handle boilerplate patterns in context lines (not just added lines)", () => {
    const diff = [
      " // Copyright 2024 Acme Corp",
      "+export function newFunc() {}",
    ].join("\n");
    const result = detectSlop(diff, 1, 0, 1, ["src/a.ts"]);
    // BOILERPLATE_RES tests against the full diffText, not just added lines
    expect(result.reasons).toContain("boilerplate markers");
  });
});
